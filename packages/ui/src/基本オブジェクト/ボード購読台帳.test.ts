import { describe, expect, it } from "vitest";
import { 開始と停止のできる購読 } from "./開始と停止のできる購読";
import { ボード購読台帳 } from "./ボード購読台帳";

class 動いているかの記録 implements 開始と停止のできる購読 {
    public 動いているか = false;
    public 始める(): void { this.動いているか = true; }
    public 止める(): void { this.動いているか = false; }
}

describe("ボード購読台帳", () => {
    it("作った直後は操作対象であり、操作対象の間だけ動かすものもすぐ動く", () => {
        const 台帳 = new ボード購読台帳();
        const 入力 = new 動いているかの記録();
        台帳.操作対象の間だけ動くものとして登録する(入力);
        expect(台帳.操作対象か).toBe(true);
        expect(入力.動いているか).toBe(true);
    });

    it("操作対象から外すと操作対象の間だけ動かすものだけが止まり、戻すと再び動く", () => {
        const 台帳 = new ボード購読台帳();
        const 常時 = new 動いているかの記録();
        const 入力 = new 動いているかの記録();
        台帳.常に動くものとして登録する(常時);
        台帳.操作対象の間だけ動くものとして登録する(入力);

        台帳.操作対象から外す();
        expect([常時.動いているか, 入力.動いているか]).toEqual([true, false]);
        台帳.操作対象にする();
        expect([常時.動いているか, 入力.動いているか]).toEqual([true, true]);
    });

    it("操作対象でない間に登録したものは、操作対象になるまで動かない", () => {
        const 台帳 = new ボード購読台帳();
        台帳.操作対象から外す();
        const 入力 = new 動いているかの記録();
        台帳.操作対象の間だけ動くものとして登録する(入力);
        expect(入力.動いているか).toBe(false);
        台帳.操作対象にする();
        expect(入力.動いているか).toBe(true);
    });

    it("すべて解除するとどちらの時期のものも止まり、以後の登録と切り替えは例外になる", () => {
        const 台帳 = new ボード購読台帳();
        const 常時 = new 動いているかの記録();
        const 入力 = new 動いているかの記録();
        台帳.常に動くものとして登録する(常時);
        台帳.操作対象の間だけ動くものとして登録する(入力);

        台帳.すべて解除する();
        expect([常時.動いているか, 入力.動いているか]).toEqual([false, false]);
        expect(() => 台帳.常に動くものとして登録する(new 動いているかの記録())).toThrow();
        expect(() => 台帳.操作対象にする()).toThrow();
        expect(() => 台帳.すべて解除する()).not.toThrow();
    });
});
