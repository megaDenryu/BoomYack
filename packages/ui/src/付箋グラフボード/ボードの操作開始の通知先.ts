/**
 * 利用者が操作対象でないボードの中を押したり、ボードの中へフォーカスを移したりしたことを受け取る側。
 * ボードを並べる側(Jimboのタブ等)が実装し、そのボードを操作対象へ切り替える。
 */
export interface ボードの操作開始の通知先 {
    ボードが操作され始めた(): void;
}

/** ボードを1枚だけ置く使い方の通知先。ボードは作った直後から操作対象のままなので、切り替えることがない。 */
export class 操作開始を知らせる先の無いボード implements ボードの操作開始の通知先 {
    public ボードが操作され始めた(): void {}
}
