import { I描画キャンバスAPIリポジトリ } from "BoomYack/基本オブジェクト/API/I描画キャンバスAPIリポジトリ";
import { ボード外部更新の受信 } from "BoomYack/基本オブジェクト/API/ボード外部更新の受信";
import { ボードの操作開始の通知先 } from "./ボードの操作開始の通知先";

/**
 * 付箋グラフのボードを作るときに渡す依存。外部更新の受信は、ボードを複数並べるときに全ボードで1つを共有させる。
 * 省いたときは、ボード1枚で使う形(受信をボードごとに作り、操作開始を知らせない)になる。
 */
export interface 付箋グラフボードの依存 {
    readonly apiリポジトリ: I描画キャンバスAPIリポジトリ;
    readonly 外部更新の受信?: ボード外部更新の受信;
    readonly 操作開始の通知先?: ボードの操作開始の通知先;
}
