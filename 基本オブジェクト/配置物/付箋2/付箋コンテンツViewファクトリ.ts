import { I付箋コンテンツView, 付箋コンテンツView共通依存関係 } from "./I付箋コンテンツView";
import { 付箋コンテンツデータ } from "../../描画キャンバス/付箋コンテンツデータ";
import { 自由テキストコンテンツView } from "./自由テキストコンテンツView";
import { タイトル付きコンテンツView } from "./タイトル付きコンテンツView";
import { 札参照コンテンツView } from "./札参照コンテンツView";
import { FudabaAPIクライアント } from "../../Fudaba連携/FudabaAPIクライアント";

/**
 * 自由テキスト・タイトル付きは使わないが、札参照コンテンツの生成にのみ必要な外部連携の依存関係。
 * 全コンテンツ種別に共通しないFudaba固有の依存を共通依存関係に混ぜず、ここで別枠に分離する。
 */
export interface 外部連携依存関係 {
    fudabaAPIクライアント: FudabaAPIクライアント;
}

/**
 * 初期コンテンツデータの種別に応じて対応するI付箋コンテンツView実装を生成する。
 * 枠(自動リサイズ付箋View)はこの関数越しにのみコンテンツを生成し、個々のコンテンツ実装
 * クラスを直接importしない。コンテンツ種別が増えてもここに1ケース足すだけでよい。
 */
export function 付箋コンテンツViewを生成する(
    初期コンテンツ: 付箋コンテンツデータ,
    共通依存関係: 付箋コンテンツView共通依存関係,
    外部連携依存関係: 外部連携依存関係
): I付箋コンテンツView {
    switch (初期コンテンツ.種別) {
        case "自由テキスト":
            return new 自由テキストコンテンツView({
                ...共通依存関係,
                初期テキスト: 初期コンテンツ.text
            });
        case "タイトル付き":
            return new タイトル付きコンテンツView({
                ...共通依存関係,
                初期タイトル: 初期コンテンツ.タイトル,
                初期本文: 初期コンテンツ.本文
            });
        case "札参照":
            return new 札参照コンテンツView({
                ...共通依存関係,
                初期札ID: 初期コンテンツ.札ID,
                fudabaAPIクライアント: 外部連携依存関係.fudabaAPIクライアント
            });
    }
}
